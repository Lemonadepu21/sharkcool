package brb02

import (
	"context"
	"encoding/binary"
	"fmt"
)

// Metric IDs follow the official screen checkbox order (EXE 0x580458),
// and the service's signal-to-system-info callbacks (0x40148a..0x401619).
type Metric string

const (
	CPUTemperature Metric = "cpu-temperature"
	GPUTemperature Metric = "gpu-temperature"
	CPUUsage       Metric = "cpu-usage"
	GPUUsage       Metric = "gpu-usage"
	FanRPM         Metric = "fan-rpm"
	DiskUsage      Metric = "disk-usage"
	MemoryUsage    Metric = "memory-usage"
	TimeOfDay      Metric = "time"
)

var metricOrder = []Metric{CPUTemperature, GPUTemperature, CPUUsage, GPUUsage, FanRPM, DiskUsage, MemoryUsage, TimeOfDay}

func metricID(metric Metric) (byte, bool) {
	for i, name := range metricOrder {
		if metric == name {
			return byte(i), true
		}
	}
	return 0, false
}

// SystemInfo carries whole degrees Celsius, whole percentages and minutes
// since local midnight. Fan RPM is generated by the device, not host-pushed.
// Missing host metrics must be omitted; zero is a valid measured value.
type SystemInfo map[Metric]uint16

func (info SystemInfo) Report() ([]byte, error) {
	if len(info) == 0 {
		return nil, fmt.Errorf("系统信息不能为空")
	}
	for metric, value := range info {
		if _, ok := metricID(metric); !ok || metric == FanRPM {
			return nil, fmt.Errorf("不能推送系统指标 %q", metric)
		}
		limit := uint16(100)
		switch metric {
		case CPUTemperature, GPUTemperature:
			limit = 150
		case TimeOfDay:
			limit = 1439
		}
		if value > limit {
			return nil, fmt.Errorf("%s 超出范围 0～%d", metric, limit)
		}
	}
	p := []byte{byte(len(info))}
	for id, metric := range metricOrder {
		if value, ok := info[metric]; ok {
			p = append(p, byte(id), 0, 0)
			binary.LittleEndian.PutUint16(p[len(p)-2:], value)
		}
	}
	packet, _ := BuildPacket(0x07, p) // Official DLL 0x1000dee0.
	return PacketReport(packet)
}

type Delivery struct {
	Sent    bool   `json:"sent"`
	Message string `json:"message"`
}

// SendSystemInfo is a one-way write, as in the official periodic service.
// Successful delivery does not prove the LCD has displayed the sample.
func (c *Controller) SendSystemInfo(ctx context.Context, info SystemInfo) (Delivery, error) {
	report, err := info.Report()
	if err != nil {
		return Delivery{}, err
	}
	return c.sendOneWay(ctx, report, "系统信息")
}

// LCDLayout uses the official three-row parameter layout. Positions 10, 143,
// 276 and trailing parameter 100 are copied from EXE 0x5807a8..0x580880;
// their physical units are not assumed. Layout selector 0: EXE 0x569374.
type LCDLayout struct {
	Rows []Metric `json:"rows"`
}

func (layout LCDLayout) Report() ([]byte, error) {
	if len(layout.Rows) != 3 {
		return nil, fmt.Errorf("屏幕布局需要三个不同指标")
	}
	seen := map[Metric]bool{}
	p := []byte{0, 0, 3}
	positions := [3]uint16{10, 143, 276}
	for i, metric := range layout.Rows {
		id, ok := metricID(metric)
		if !ok || seen[metric] {
			return nil, fmt.Errorf("无效或重复的屏幕指标 %q", metric)
		}
		seen[metric] = true
		p = append(p, id, byte(positions[i]), byte(positions[i]>>8), 100)
	}
	packet, _ := BuildPacket(0xc2, p) // Official DLL 0x1000e330.
	return PacketReport(packet)
}

type LCDResult struct {
	Acknowledged bool   `json:"acknowledged"`
	Message      string `json:"message"`
}

func (f Frame) LCDEnabled() (bool, error) {
	if f.Command != 0xc1 || len(f.Payload) != 1 || f.Payload[0] > 1 {
		return false, fmt.Errorf("无法识别屏幕开关响应 %x", f.Payload)
	}
	return f.Payload[0] == 1, nil
}

func (c *Controller) SetLCDLayout(ctx context.Context, layout LCDLayout) (LCDResult, error) {
	report, err := layout.Report()
	if err != nil {
		return LCDResult{}, err
	}
	f, err := c.exchange(ctx, report)
	if err != nil {
		return LCDResult{}, err
	}
	if len(f.Payload) != 1 || f.Payload[0] != 0 {
		return LCDResult{}, fmt.Errorf("屏幕布局未返回成功响应: %x", f.Payload)
	}
	return LCDResult{true, "设备已接受屏幕布局；请在散热器上核对三行显示"}, nil
}
